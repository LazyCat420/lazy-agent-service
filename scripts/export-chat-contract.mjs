import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const wire = JSON.parse(fs.readFileSync(path.join(root, 'contracts/generated/runtime-wire-v1.json'), 'utf8'));
const pkg = path.join(root, 'packages/agent-chat');
const event = wire.schema.properties.run_event;
const names = event.properties.type.enum;
// Derive the envelope from the authoritative generated JSON schema. Fail the
// build when a future field needs explicit generator support.
function type(schema) {
  if (schema.enum) return schema.enum.map(JSON.stringify).join(' | ');
  if (schema.type === 'string') return 'string';
  if (schema.type === 'object') return 'T';
  throw new Error(`Unsupported event schema: ${JSON.stringify(schema)}`);
}
const fields = Object.entries(event.properties).map(([key, value]) =>
  `  ${key}${event.required.includes(key) ? '' : '?'}: ${key === 'type' ? 'CanonicalEventType' : type(value)};`);
fs.writeFileSync(path.join(pkg, 'src/generated-contract.ts'),
  `// Generated by scripts/export-chat-contract.mjs; do not edit.\n` +
  `export const EVENT_TYPES = ${JSON.stringify(names)} as const;\n` +
  `export type CanonicalEventType = typeof EVENT_TYPES[number];\n` +
  `export interface RuntimeEvent<T = Record<string, any>> {\n${fields.join('\n')}\n}\n`);
const manifest = {
  package_version: JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'))).version,
  contract_version: wire.contract_version,
  contract_digest: wire.digest,
  minimum_runtime_version: JSON.parse(fs.readFileSync(path.join(root, 'package.json'))).version,
};
fs.writeFileSync(path.join(pkg, 'contract.json'), JSON.stringify(manifest, null, 2) + '\n');
